
import json
import re

from app.llm.client import generate_from_messages


JUDGE_PROMPT = """
You are an impartial evaluator grading an answer generated by a
Retrieval-Augmented Generation (RAG) system.

Evaluate the answer using ONLY the question and provided context.

Scoring criteria:
1. faithfulness: How well is the answer supported by the context?
2. relevance: How directly does the answer address the question?
3. completeness: Does the answer cover the important information
   needed to answer the question?

Give each score as a number between 0.0 and 1.0.

Be strict:
- Unsupported claims should reduce faithfulness.
- Irrelevant information should reduce relevance.
- Missing important information should reduce completeness.
- Do not reward an answer simply because it sounds confident.

Question:
{question}

Context:
{context}

Answer:
{answer}

Return ONLY a JSON object with exactly these keys:
{{
  "faithfulness": 0.0,
  "relevance": 0.0,
  "completeness": 0.0,
  "reason": "Briefly explain the scores."
}}
"""


def judge(question: str, context: str, answer: str) -> dict:
    """Evaluate a RAG answer and return structured scores."""

    if not isinstance(question, str) or not question.strip():
        raise ValueError("Question cannot be empty.")

    if not isinstance(context, str) or not context.strip():
        raise ValueError("Context cannot be empty.")

    if not isinstance(answer, str) or not answer.strip():
        raise ValueError("Answer cannot be empty.")

    messages = [
        {
            "role": "system",
            "content": (
                "You are a strict RAG evaluation judge. "
                "Return valid JSON only, without Markdown fences."
            ),
        },
        {
            "role": "user",
            "content": JUDGE_PROMPT.format(
                question=question,
                context=context,
                answer=answer,
            ),
        },
    ]

    response = generate_from_messages(messages)
    response_text = response.get("text", "")

    if not isinstance(response_text, str) or not response_text.strip():
        raise ValueError(
            f"Gemini returned empty text. Full response: {response}"
        )

    response_text = response_text.strip()

    # Remove Markdown fences if Gemini wraps the JSON in ```json ... ```.
    if response_text.startswith("```"):
        response_text = re.sub(
            r"\A```(?:json)?\s*|\s*```\Z",
            "",
            response_text,
            flags=re.IGNORECASE,
        ).strip()

    try:
        result = json.loads(response_text)
    except json.JSONDecodeError as error:
        raise ValueError(
            "Gemini did not return valid JSON.\n"
            f"Raw response: {response_text!r}"
        ) from error

    if not isinstance(result, dict):
        raise ValueError("Judge response must be a JSON object.")

    required_keys = {
        "faithfulness",
        "relevance",
        "completeness",
        "reason",
    }

    missing_keys = required_keys - set(result.keys())

    if missing_keys:
        raise ValueError(
            f"Judge response is missing required fields: {sorted(missing_keys)}"
        )

    for key in ("faithfulness", "relevance", "completeness"):
        score = result[key]

        if (
            isinstance(score, bool)
            or not isinstance(score, (int, float))
            or not 0.0 <= score <= 1.0
        ):
            raise ValueError(
                f"{key} must be a number between 0.0 and 1.0."
            )

        result[key] = float(score)

    if not isinstance(result["reason"], str):
        raise ValueError("reason must be a string.")

    return result


if __name__ == "__main__":
    sample_result = judge(
        question="What is Natural Language Processing?",
        context=(
            "Natural Language Processing (NLP) is a branch of "
            "Artificial Intelligence that enables computers to "
            "understand and process human language."
        ),
        answer=(
            "NLP is a branch of AI that helps computers "
            "understand and process human language."
        ),
    )

    print(json.dumps(sample_result, indent=2))
